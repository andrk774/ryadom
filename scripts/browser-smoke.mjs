import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import sharp from 'sharp';
import { createApp } from '../server/app.js';

const tempRoot = path.resolve(os.tmpdir());
const dir = fs.mkdtempSync(path.join(tempRoot, 'ryadom-browser-'));
const mail = [];
const app = createApp({ dataDir: dir, moderationRequired: true, sendMail: async m => mail.push(m), captchaSiteKey:'browser-test',
  verifyCaptcha:async token=>({success:token==='browser-token',hostname:'127.0.0.1',action:'submit'}) });
await new Promise(r => app.server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${app.server.address().port}`;
let browser;
const errors = [];
try {
  browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_EXECUTABLE || undefined });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  page.on('dialog', dialog => dialog.type() === 'beforeunload' ? dialog.accept() : dialog.accept('Тестовая жалоба'));
  await page.goto(base + '/#/register');
  await page.locator('#register input[name=name]').fill('Продавец');
  await page.locator('#register input[name=email]').fill('seller@example.test');
  await page.locator('#register input[name=password]').fill('password123');
  await page.locator('#register button[type=submit]').click();
  await page.waitForSelector('#save-search');
  const seller = app.db.prepare('SELECT * FROM users WHERE email = ?').get('seller@example.test');
  assert.ok(seller);
  const token = mail.at(-1).text.match(/token=([\w-]+)/)[1];
  await page.goto(base + '/#/verify?token=' + token);
  await page.getByRole('button', {name:'Подтвердить email', exact:true}).click();
  await page.waitForSelector('#profile');
  await page.locator('#profile [name=about]').fill('Проверенный профиль продавца');
  await page.locator('#profile button[type=submit]').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent === 'Профиль сохранён');
  await page.goto(base + '/#/new');
  await page.waitForSelector('#editor');
  await page.locator('#editor [name=title]').fill('Lada тестовое объявление');
  await page.locator('#editor [name=category]').selectOption('transport');
  await page.locator('#editor [name=price]').fill('15000');
  await page.locator('#editor [name=attr_brand]').fill('Lada');
  await page.locator('#editor [name=attr_year]').fill('2021');
  await page.locator('#editor [name=description]').fill('Подробное описание тестового автомобиля.');
  await page.locator('#editor [name=district]').fill('Центральный');
  await page.locator('#editor details summary').click();
  await page.locator('#editor [name=latitude]').fill('55.75');
  await page.locator('#editor [name=longitude]').fill('37.61');
  const photo = await sharp({create:{width:40,height:20,channels:3,background:'red'}}).png().toBuffer();
  let releaseUpload, startedUpload;
  const uploadStarted = new Promise(r => { startedUpload = r; });
  const uploadGate = new Promise(r => { releaseUpload = r; });
  await page.route('**/api/uploads', async route => { startedUpload(); await uploadGate; await route.continue(); });
  await page.locator('#photos input').setInputFiles({ name: 'photo.png', mimeType: 'image/png', buffer: photo });
  await uploadStarted;
  assert.equal(await page.locator('#editor button[type=submit]').isDisabled(), true, 'publication disabled while uploading');
  releaseUpload();
  await page.waitForSelector('#photos img');
  await page.unroute('**/api/uploads');
  await page.locator('[data-photo-action=rotate]').click();
  await page.waitForFunction(() => !document.querySelector('#editor button[type=submit]').disabled);
  await page.locator('#preview-button').click();
  assert.equal(await page.locator('#preview').isVisible(), true);
  await page.locator('#save-draft').click();
  await page.waitForFunction(() => document.querySelector('#draft-state').textContent === 'Черновик сохранён');
  const draftUrl = page.url();
  assert.match(draftUrl, /#\/draft\/\d+/);
  await page.reload();
  await page.waitForSelector('#editor');
  assert.equal(await page.locator('#editor [name=title]').inputValue(), 'Lada тестовое объявление');
  assert.equal(await page.locator('#photos img').count(), 1);
  await page.locator('#editor button[type=submit]').click();
  await page.waitForSelector('.notice');
  assert.match(await page.locator('.notice').textContent(), /На проверке/);
  const listingId = Number(page.url().match(/listing\/(\d+)/)[1]);
  assert.equal(app.db.prepare('SELECT COUNT(*) AS n FROM drafts').get().n, 0);
  app.db.prepare("UPDATE users SET role = 'admin' WHERE id = ?").run(seller.id);
  await page.reload();
  await page.goto(base + '/#/admin');
  await page.waitForSelector('[data-moderate=approved]');
  await page.locator('[data-moderate=approved]').click();
  await page.waitForFunction(() => !document.querySelector('[data-moderate=approved]'));
  assert.equal(app.db.prepare('SELECT moderation FROM listings WHERE id = ?').get(listingId).moderation, 'approved');
  await page.goto(base + '/#/?category=transport');
  await page.waitForSelector('#filters [name=attr_year_min]');
  await page.locator('#filters [name=attr_year_min]').fill('2022');
  await page.locator('#filters button[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('.card'));
  await page.goto(base + '/#/?category=transport&attr_year_min=2020');
  await page.waitForSelector('.card');
  await page.locator('#save-search').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent.startsWith('Поиск сохранён'));
  await page.goto(base + '/#/searches');
  await page.waitForSelector('[data-delete-search]');
  await page.goto(base + '/#/notifications');
  await page.waitForSelector('.row-item');

  const buyer = await browser.newPage({ viewport: {width:390,height:844} });
  buyer.on('pageerror', error => errors.push(error.message));
  await buyer.goto(base + '/#/register');
  await buyer.locator('#register [name=name]').fill('Покупатель');
  await buyer.locator('#register [name=email]').fill('buyer@example.test');
  await buyer.locator('#register [name=password]').fill('password123');
  await buyer.locator('#register button[type=submit]').click();
  await buyer.waitForSelector('#save-search');
  await buyer.goto(base + '/#/listing/' + listingId);
  await buyer.waitForSelector('#contact');
  await buyer.locator('#contact button[type=submit]').click();
  await buyer.waitForSelector('#send');
  const conv = app.db.prepare('SELECT id FROM conversations LIMIT 1').get().id;
  const insert = app.db.prepare('INSERT INTO messages (conversation_id,sender_id,text,created_at) VALUES (?,?,?,?)');
  for (let i=0;i<70;i++) insert.run(conv,seller.id,`Сообщение ${i}`,Date.now());
  await buyer.reload();
  await buyer.waitForSelector('#older:not([hidden])');
  await buyer.locator('#older').click();
  await buyer.waitForFunction(() => document.querySelectorAll('.msg').length === 71);
  await buyer.locator('#chat-files').setInputFiles({name:'chat.png',mimeType:'image/png',buffer:photo});
  await buyer.waitForSelector('[data-remove-attachment]');
  await buyer.locator('#send button').click();
  await buyer.waitForSelector('.chat-photo');
  await buyer.locator('#block-chat').click();
  await buyer.waitForFunction(() => document.querySelector('#send button')?.disabled === true);
  await buyer.goto(base + '/#/blocks');
  await buyer.waitForSelector('[data-unblock]');
  await buyer.locator('[data-unblock]').click();
  await buyer.waitForFunction(() => !document.querySelector('[data-unblock]'));
  await buyer.goto(base + '/#/messages/' + conv);
  await buyer.waitForSelector('#send button:not([disabled])');
  assert.equal(await buyer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'no mobile horizontal overflow');
  fs.mkdirSync('.qa', {recursive:true});
  await buyer.screenshot({path:'.qa/mobile-chat.png',fullPage:true});
  await page.goto(base + '/#/settings');
  await page.waitForSelector('#profile');
  await page.locator('#preferences [name=emailNotifications]').selectOption('true');
  await page.locator('#preferences button').click();
  await page.waitForFunction(() => document.querySelector('#toast').textContent === 'Настройка сохранена');
  await page.screenshot({path:'.qa/desktop-settings.png',fullPage:true});
  await page.goto(base + '/#/stats');
  await page.waitForSelector('tbody tr');
  assert.match(await page.locator('table').first().textContent(), /Lada/);
  await app.maintenance();
  await page.goto(base + '/#/operations');
  await page.getByText('Последняя проверенная копия:', {exact:false}).waitFor();
  await page.context().grantPermissions(['geolocation']);
  await page.context().setGeolocation({latitude:55.75,longitude:37.61});
  await page.goto(base + '/#/?category=transport');
  await page.waitForSelector('#near-me');
  await page.locator('#near-me').click();
  await page.waitForURL(/radius=10/);
  await page.waitForSelector('.card');
  assert.equal(await page.locator('.card').count(),1);
  await buyer.goto(base + '/#/new');
  await buyer.waitForSelector('#editor');
  assert.equal(await buyer.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, 'editor fits mobile');
  await buyer.screenshot({path:'.qa/mobile-editor.png',fullPage:true});
  const challenge = await browser.newPage();
  challenge.on('pageerror',error=>errors.push(error.message));
  await challenge.addInitScript(()=>{
    window.turnstile={render:(element,options)=>{const button=document.createElement('button');button.textContent='Test CAPTCHA';button.onclick=()=>options.callback('browser-token');element.append(button);return 1;},remove:()=>{}};
  });
  await challenge.goto(base+'/#/login');
  for(let i=0;i<5;i++)await challenge.request.post(base+'/api/auth/login',{data:{email:'seller@example.test',password:'wrong-password'}});
  await challenge.locator('#login [name=email]').fill('seller@example.test');
  await challenge.locator('#login [name=password]').fill('password123');
  await challenge.locator('#login button').click();
  await challenge.getByRole('button',{name:'Test CAPTCHA'}).click();
  await challenge.waitForSelector('#save-search');
  assert.deepEqual(errors, []);
  console.log('Browser smoke passed: account, verification, settings, uploads, drafts, moderation, notifications, chat blocking, stats, location, operations, CAPTCHA and mobile layouts.');
} finally {
  await browser?.close(); await app.close();
  assert.equal(path.dirname(path.resolve(dir)), tempRoot);
  assert.ok(path.basename(dir).startsWith('ryadom-browser-'));
  fs.rmSync(dir,{recursive:true,force:true});
}
